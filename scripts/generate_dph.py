"""Generate `src/czreg/dph/models.py` from the rozhraniCRPDPH WSDL of the Financial Administration.

uv run scripts/generate_dph.py              # from the committed specs/dph/
uv run scripts/generate_dph.py --download   # fetch the current WSDL first
"""

import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from subprocess import run

import httpx

URL = "https://mojedane.gov.cz/dpr/axis2/services/rozhraniCRPDPH.rozhraniCRPDPHSOAP"
ROOT = Path(__file__).resolve().parent.parent
WSDL = ROOT / "specs" / "dph" / "rozhraniCRPDPH.wsdl"
MODELS = ROOT / "src" / "czreg" / "dph" / "models.py"


def main():
    if "--download" in sys.argv:
        WSDL.write_bytes(httpx.get(f"{URL}?wsdl").raise_for_status().content)

    schema = ET.parse(WSDL).find(".//{http://www.w3.org/2001/XMLSchema}schema")
    assert schema is not None
    xsd = Path(tempfile.mkdtemp()) / "rozhraniCRPDPH.xsd"
    ET.ElementTree(schema).write(xsd, encoding="utf-8", xml_declaration=True)

    run(
        [
            "datamodel-codegen",
            "--input",
            str(xsd),
            "--input-file-type",
            "xmlschema",
            "--output",
            str(MODELS),
            "--custom-file-header",
            "# Generated by scripts/generate_dph.py from specs/dph/. Do not edit.",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--base-class",
            "czreg._core.base.CzregModel",
            "--use-annotated",  # Field() inside Annotated, so the defaults type-check
            "--collapse-root-models",  # `dic: list[str]`, not `list[DICType]`
            "--use-object-type",  # `dict[str, object]`, not `dict[str, Any]`, for the empty request
            "--target-python-version",
            "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--disable-timestamp",
            "--formatters",
            "ruff-check",
            "ruff-format",
        ],
        check=True,
        cwd=ROOT,
    )


if __name__ == "__main__":
    main()
