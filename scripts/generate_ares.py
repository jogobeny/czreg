"""Generate `src/czreg/ares/models/` from the ARES OpenAPI spec.

uv run scripts/generate_ares.py              # from the committed specs/ares/
uv run scripts/generate_ares.py --download   # fetch the current spec first
"""

import json
import shutil
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path
from subprocess import run
from typing import cast

import httpx

URL = "https://ares.gov.cz/ekonomicke-subjekty-v-be/rest/v3/api-docs"
ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "specs" / "ares" / "openapi.json"
MODELS = ROOT / "src" / "czreg" / "ares" / "models"

CONSTRAINTS = {"maxLength", "minLength", "pattern", "minimum", "maximum", "maxItems", "minItems"}
TAG_MODULES = {
    "ekonomicke-subjekty": "ekonomicke_subjekty",
    "ciselniky-nazevniky": "ciselniky",
    "standardizovane-adresy": "adresy",
}

type Json = dict[str, Json] | list[Json] | str | int | float | bool | None
type Obj = dict[str, Json]


def walk(node: Json) -> Iterator[Obj]:
    """Every dict in the tree."""
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from walk(value)
    elif isinstance(node, list):
        for value in node:
            yield from walk(value)


def refs(node: Json) -> Iterator[str]:
    for d in walk(node):
        if isinstance(ref := d.get("$ref"), str):
            yield ref.rsplit("/", 1)[-1]


def assign_modules(paths: dict[str, dict[str, Obj]], schemas: dict[str, Json]):
    """Map each schema to the module of the register that uses it, or to `common`."""
    users: dict[str, set[str]] = {name: set() for name in schemas}
    for operations in paths.values():
        for op in operations.values():
            tag = cast("list[str]", op["tags"])[0]
            module = TAG_MODULES.get(tag) or tag.removeprefix("ekonomicke-subjekty-")
            todo = list(refs(op))
            while todo:
                name = todo.pop()
                if module not in users[name]:
                    users[name].add(module)
                    todo.extend(refs(schemas[name]))
    return {name: m.pop() if len(m) == 1 else "common" for name, m in users.items()}


def main():
    if "--download" in sys.argv:
        SPEC.write_bytes(httpx.get(URL).raise_for_status().content)

    spec = cast("Obj", json.loads(SPEC.read_bytes()))
    paths = cast("dict[str, dict[str, Obj]]", spec["paths"])
    components = cast("Obj", spec["components"])
    schemas = cast("Obj", components["schemas"])

    for d in walk(spec):
        for key in CONSTRAINTS & d.keys():
            del d[key]

    modules = assign_modules(paths, schemas)
    for d in walk(spec):
        if isinstance(ref := d.get("$ref"), str):
            name = ref.rsplit("/", 1)[-1]
            d["$ref"] = f"#/components/schemas/{modules[name]}.{name}"
    components["schemas"] = {f"{modules[n]}.{n}": s for n, s in schemas.items()}

    tmp = Path(tempfile.mkdtemp()) / SPEC.name
    tmp.write_text(json.dumps(spec, ensure_ascii=False))
    shutil.rmtree(MODELS, ignore_errors=True)

    run(
        [
            "datamodel-codegen",
            "--input",
            str(tmp),
            "--input-file-type",
            "openapi",
            "--output",
            str(MODELS),
            "--custom-file-header",
            "# Generated by scripts/generate_ares.py from specs/ares/. Do not edit.",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--base-class",
            "czreg._core.base.CzregModel",
            "--use-annotated",  # Field() inside Annotated, so the defaults type-check
            "--treat-dot-as-module",
            "--use-exact-imports",  # `from .common import X`, not `from . import common` (cycle)
            "--all-exports-scope",
            "recursive",
            "--target-python-version",
            "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--use-schema-description",
            "--use-field-description",
            "--disable-timestamp",
            "--formatters",
            "ruff-check",
            "ruff-format",
        ],
        check=True,
        cwd=ROOT,
    )


if __name__ == "__main__":
    main()
