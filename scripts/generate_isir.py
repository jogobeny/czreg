"""Generate `src/czreg/isir/models.py` from the ISIR_CUZK_WS XSD.

uv run scripts/generate_isir.py              # from the committed specs/isir/
uv run scripts/generate_isir.py --download   # fetch the current WSDL and XSD first
"""

import sys
from pathlib import Path
from subprocess import run

import httpx

URL = "https://isir.justice.cz:8443/isir_cuzk_ws/IsirWsCuzkService"
ROOT = Path(__file__).resolve().parent.parent
WSDL = ROOT / "specs" / "isir" / "isir_cuzk.wsdl"
XSD = ROOT / "specs" / "isir" / "isir_cuzk.xsd"
MODELS = ROOT / "src" / "czreg" / "isir" / "models.py"


def main():
    if "--download" in sys.argv:
        for url, path in ((f"{URL}?wsdl", WSDL), (f"{URL}?xsd=isirWsCuzkTypes.xsd", XSD)):
            path.write_bytes(httpx.get(url).raise_for_status().content)

    run(
        [
            "datamodel-codegen",
            "--input",
            str(XSD),
            "--input-file-type",
            "xmlschema",
            "--output",
            str(MODELS),
            "--custom-file-header",
            "# Generated by scripts/generate_isir.py from specs/isir/. Do not edit.",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--base-class",
            "czreg._core.base.CzregModel",
            "--use-annotated",  # Field() inside Annotated, so the defaults type-check
            "--target-python-version",
            "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--disable-timestamp",
            "--formatters",
            "ruff-check",
            "ruff-format",
        ],
        check=True,
        cwd=ROOT,
    )


if __name__ == "__main__":
    main()
